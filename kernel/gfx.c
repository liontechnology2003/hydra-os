{
    text_fg = fg;
    text_bg = bg;
}

void gfx_scroll_text(void)
{
    vbe_info_t *v = vbe_get_info();
    uint32 pitch = fb_pitch_words();
    uint32 row;

    /* Move all rows up by char_h pixels */
    uint32 *lfb_ptr = lfb();

    for (row = 0; row < v->height - char_h; row++) {
        uint32 *dst = lfb_ptr + row * pitch;
        uint32 *src = lfb_ptr + (row + char_h) * pitch;
        uint32 col;
        for (col = 0; col < v->width; col++) {
            dst[col] = src[col];
        }
    }

    /* Clear bottom lines */
    gfx_fill_rect(0, v->height - char_h, v->width, char_h, text_bg);
    text_y = v->height - char_h;
}

void gfx_text_putchar(char c)
{
    vbe_info_t *v = vbe_get_info();

    if (c == '\n') {
        text_x = 0;
        text_y += char_h;
    } else if (c == '\b') {
        if (text_x >= char_w) {
            text_x -= char_w;
        }
    } else if (c == '\t') {
        text_x = (text_x + char_w * 8) & ~(char_w * 8 - 1);
    } else {
        gfx_put_char(text_x, text_y, c, text_fg, text_bg, text_scale);
        text_x += char_w;
    }

    if (text_x + char_w > v->width) {
        text_x = 0;
        text_y += char_h;
    }

    if (text_y + char_h > v->height) {
        gfx_scroll_text();
    }
}

void gfx_text_puts(const char *str)
{
    while (*str) {
        gfx_text_putchar(*str);
        str++;
    }
}

