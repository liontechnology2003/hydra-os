void gfx_set_damage(uint32 x, uint32 y, uint32 w, uint32 h)
{
    if (!damage_flag) {
        damage.x = x; damage.y = y;
        damage.w = w; damage.h = h;
        damage_flag = 1;
    } else {
        /* Expand damage region */
        uint32 dx1 = damage.x < x ? damage.x : x;
        uint32 dy1 = damage.y < y ? damage.y : y;
        uint32 dx2 = (damage.x + damage.w) > (x + w) ? (damage.x + damage.w) : (x + w);
        uint32 dy2 = (damage.y + damage.h) > (y + h) ? (damage.y + damage.h) : (y + h);
        damage.x = dx1; damage.y = dy1;
        damage.w = dx2 - dx1; damage.h = dy2 - dy1;
    }
}

int gfx_has_damage(void)
{
    return damage_flag;
}

void gfx_get_damage(gfx_rect_t *rect)
{
    if (rect) *rect = damage;
}

void gfx_clear_damage(void)
{
    damage_flag = 0;
    damage.x = damage.y = damage.w = damage.h = 0;
}
